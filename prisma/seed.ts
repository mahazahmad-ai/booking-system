/**
 * Realistic demo data for Glow & Grace.
 *
 * Bookings are not hard-coded times. They are generated by running the real
 * `computeSlots()` against each therapist's working rules and time off, then booking into
 * slots it returns — with every booking created so far fed back in as blocked time. That
 * means the seed cannot produce a booking the exclusion constraint would reject, and
 * seeding doubles as an end-to-end exercise of the availability engine.
 *
 *   npm run db:seed
 */

