/**
 * Weekly hours as minutes from local midnight. Weekdays are split around a lunch break,
 * which is the FR-A6 case — several rows per day, not one span.
 */
function rulesFor(dayOfWeek: number): { startMin: number; endMin: number }[] {
  if (dayOfWeek === 0) return [] // Sunday, closed
  if (dayOfWeek === 6) return [{ startMin: 600, endMin: 960 }] // Sat 10:00–16:00
  return [
    { startMin: 600, endMin: 780 }, // 10:00–13:00
    { startMin: 840, endMin: 1140 }, // 14:00–19:00
  ]
}

